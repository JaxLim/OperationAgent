import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const lab = fileURLToPath(new URL('./', import.meta.url));
const root = resolve(lab, '../..');
const lock = JSON.parse(await readFile(resolve(root, 'build/runtime-lock.json'), 'utf8'));
if (process.platform !== 'win32' || process.arch !== 'x64' || process.version !== `v${lock.node}`) throw new Error('Locked Windows x64 runtime required');
const vswhere = 'C:/Program Files (x86)/Microsoft Visual Studio/Installer/vswhere.exe';
const installation = spawnSync(vswhere, ['-latest', '-products', '*', '-requires', 'Microsoft.VisualStudio.Component.VC.Tools.x86.x64', '-property', 'installationPath'], { encoding: 'utf8', windowsHide: true });
if (installation.status !== 0) throw new Error('Visual Studio discovery failed');
const vs = installation.stdout.trim();
const msvcVersion = (await readFile(resolve(vs, 'VC/Auxiliary/Build/Microsoft.VCToolsVersion.default.txt'), 'utf8')).trim();
const msvc = resolve(vs, 'VC/Tools/MSVC', msvcVersion);
const sdk = process.env.DEC001_WINDOWS_SDK ?? 'C:/Program Files (x86)/Windows Kits/10';
const sdkVersion = process.env.DEC001_WINDOWS_SDK_VERSION ?? '10.0.26100.0';
const output = resolve(lab, '_build/native');
await mkdir(output, { recursive: true });
await mkdir(resolve(lab, '_tmp'), { recursive: true });
const includes = [resolve(msvc, 'include'), ...['ucrt', 'shared', 'um', 'winrt'].map(x => resolve(sdk, 'Include', sdkVersion, x))];
const libs = [resolve(msvc, 'lib/x64'), ...['ucrt', 'um'].map(x => resolve(sdk, 'Lib', sdkVersion, x, 'x64'))];
const compiler = resolve(msvc, 'bin/Hostx64/x64/cl.exe');
const args = ['/nologo', '/LD', '/MT', '/std:c++20', '/EHsc', '/W4', '/WX', '/O2', '/utf-8', '/D_WIN32_WINNT=0x0A00', '/DNODE_GYP_MODULE_NAME=dec001', `/I${resolve(lab, '_downloads', `node-v${lock.node}`, 'include/node')}`, `/Fo${resolve(output, 'probe.obj')}`, `/Fd${resolve(output, 'probe.pdb')}`, resolve(lab, 'native/probe.cc'), '/link', `/OUT:${resolve(output, 'probe.node')}`, `/IMPLIB:${resolve(output, 'probe.lib')}`, resolve(lab, '_downloads/node.lib'), 'advapi32.lib', 'userenv.lib', 'bcrypt.lib', 'ws2_32.lib'];
const env = { ...process.env, INCLUDE: includes.join(';'), LIB: libs.join(';'), PATH: `${resolve(msvc, 'bin/Hostx64/x64')};${process.env.PATH}`, TMP: resolve(lab, '_tmp'), TEMP: resolve(lab, '_tmp') };
const result = spawnSync(compiler, args, { cwd: output, env, windowsHide: true, shell: false });
const decoder = new TextDecoder('gb18030');
const stdout = decoder.decode(result.stdout ?? Buffer.alloc(0));
const stderr = decoder.decode(result.stderr ?? Buffer.alloc(0));
const evidence = { compiler, msvcVersion, sdkVersion, node: process.version, args, status: result.status, stdout, stderr, rawStdoutBase64: result.stdout?.toString('base64'), rawStderrBase64: result.stderr?.toString('base64') };
await writeFile(resolve(output, 'build-result.json'), JSON.stringify(evidence, null, 2) + '\n');
process.stdout.write(stdout); process.stderr.write(stderr);
if (result.error || result.status !== 0) throw new Error('Native experiment build failed', { cause: result.error });
console.log('Built experimental Node-API addon; not a production sandbox.');
